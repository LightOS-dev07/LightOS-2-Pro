/*
 * LightOS Extended 8x8 Font
 *  - ASCII 0x20-0x7F  : font_ascii[cp - 0x20]
 *  - Türkçe özel      : font_ext[id]  (id = ext_glyph_id(codepoint))
 *  - Matematik sembol : font_ext[id]  (aynı tablo, TR'nin devamı)
 *
 * EXT index map:
 *   0=Ç  1=Ğ  2=İ  3=Ö  4=Ş  5=Ü
 *   6=ç  7=ğ  8=ı  9=ö  10=ş 11=ü
 *   12=× 13=÷ 14=± 15=≤ 16=≥ 17=≠
 *   18=√ 19=π 20=∞ 21=° 22=² 23=³
 *   24=¼ 25=½ 26=¾ 27=µ 28=∑ 29=∫
 *   30=□ (bilinmeyen karakter placeholder'ı — DrawCharCP fallback'i)
 */

/* Türkçe olmayan latin ek (0xC7,0xD6,0xDC,0xE7,0xF6,0xFC)
   font_ext içinde tutuluyor, ayrı array gerekmez. */

static int ext_glyph_id(unsigned int cp) {
    switch(cp) {
        case 0x00C7: return 0;  /* Ç */
        case 0x011E: return 1;  /* Ğ */
        case 0x0130: return 2;  /* İ */
        case 0x00D6: return 3;  /* Ö */
        case 0x015E: return 4;  /* Ş */
        case 0x00DC: return 5;  /* Ü */
        case 0x00E7: return 6;  /* ç */
        case 0x011F: return 7;  /* ğ */
        case 0x0131: return 8;  /* ı */
        case 0x00F6: return 9;  /* ö */
        case 0x015F: return 10; /* ş */
        case 0x00FC: return 11; /* ü */
        /* ── Matematik / bilimsel semboller ── */
        case 0x00D7: return 12; /* × çarpı */
        case 0x00F7: return 13; /* ÷ bölü */
        case 0x00B1: return 14; /* ± artı-eksi */
        case 0x2264: return 15; /* ≤ küçük eşit */
        case 0x2265: return 16; /* ≥ büyük eşit */
        case 0x2260: return 17; /* ≠ eşit değil */
        case 0x221A: return 18; /* √ karekök */
        case 0x03C0: return 19; /* π pi */
        case 0x221E: return 20; /* ∞ sonsuz */
        case 0x00B0: return 21; /* ° derece */
        case 0x00B2: return 22; /* ² üstü 2 */
        case 0x00B3: return 23; /* ³ üstü 3 */
        case 0x00BC: return 24; /* ¼ */
        case 0x00BD: return 25; /* ½ */
        case 0x00BE: return 26; /* ¾ */
        case 0x00B5: return 27; /* µ mikro */
        case 0x2211: return 28; /* ∑ toplam */
        case 0x222B: return 29; /* ∫ integral */
        default: return -1;
    }
}
/* Geriye dönük uyum: eski isimle çağıran kod varsa çalışmaya devam etsin */
static inline int tr_glyph_id(unsigned int cp){ return ext_glyph_id(cp); }

